"""Build switch/chakshu-room.template.yaml from the base template and the policies.

    python scripts/build_room_template.py

Each file in knowledge/policies/ (except README.md) becomes one room document. Its first
line ("# AML-01 Alert triage and escalation") gives the document's name and description.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "switch" / "room-template.base.yaml"
POLICIES = ROOT / "knowledge" / "policies"
OUT = ROOT / "switch" / "chakshu-room.template.yaml"
INDENT = "    "  # the docs list sits under room:


def doc_entry(path: Path) -> str:
    text = path.read_text(encoding="utf-8").strip()
    title = text.splitlines()[0].lstrip("# ").strip()
    doc_id, _, description = title.partition(" ")
    body = "\n".join(INDENT + "    " + line if line else "" for line in text.splitlines())
    return (
        f"{INDENT}- name: {doc_id}\n"
        f"{INDENT}  description: {description}\n"
        f"{INDENT}  instructions: Read before recommending; cite as \"per {doc_id}\".\n"
        f"{INDENT}  content: |\n{body}\n"
    )


def main() -> None:
    base = BASE.read_text(encoding="utf-8")
    if base.count("__DOCS__") != 1:
        raise SystemExit(f"{BASE} must contain the line __DOCS__ exactly once")
    files = sorted(p for p in POLICIES.glob("*.md") if p.name != "README.md")
    if not files:
        raise SystemExit(f"no policy documents found in {POLICIES}")
    docs = "".join(doc_entry(p) for p in files).rstrip("\n")
    header = "# GENERATED by scripts/build_room_template.py. Edit room-template.base.yaml\n# and knowledge/policies/ instead, then rebuild.\n"
    OUT.write_text(header + base.replace("__DOCS__", docs), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)} with {len(files)} room documents")


if __name__ == "__main__":
    main()
